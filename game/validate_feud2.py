def line(tag, r):
    return f"  {tag:<10} 겹침 {r['score']:.2f} · 1위 {'✓' if r['top1'] else '✗'} · 상위3 {r['top3']}/3 | 목록 밖: {r['outside'][:3]}"


def head(real, r, k=6):
    top = sorted([x for x in real if real[x] is not None], key=lambda x: -real[x])[:k]
    return "    실측/AI: " + " ".join(f"{x} {real[x]:g}/{r['ai'][x]:g}" for x in top)


async def main(n, seed, styles):
    router = Router(budget_usd=3.0)
    people = sample(load(), "Korea", n, seed)
    out = []

    async def run(part, q, real, target, old_q=None):
        print(f"\n[{part}] {q}", flush=True)
        for st in styles:
            r = await one(router, people, q, real, st, target)
            rec = {"part": part, "q": q, "style": st, **{k: v for k, v in r.items() if k != "rows"}}
            print(line(st, r)); print(head(real, r))
            if old_q and st == "D":   # 같은 D 출력을 2019 실측에 채점
                r19 = await one(router, people, old_q, OLD[old_q], st, rows=r["rows"])
                rec["score_vs_2019"] = r19["score"]
                print(line("D→2019", r19))
            out.append(rec)

    for q, real, old_q in REPEAT:
        await run("repeat24", q, real, T24, old_q)
    for q, real in NEW.items():
        await run("new24", q, real, T24)
    for q, real, target in Y26:
        await run("y2026", q, real, target)

    print("\n=== 평균 겹침 ===")
    for part in ["repeat24", "new24", "y2026"]:
        print(part, " ".join(f"{st} {sum(o['score'] for o in out if o['part'] == part and o['style'] == st) / sum(1 for o in out if o['part'] == part and o['style'] == st):.3f}" for st in styles))
    d = [o for o in out if o["part"] == "repeat24" and o["style"] == "D"]
    if d:
        print(f"D 반복 12문항: 2024 기준 {sum(o['score'] for o in d) / len(d):.3f} vs 2019 기준 {sum(o['score_vs_2019'] for o in d) / len(d):.3f}, "
              f"2024 쪽이 높은 문항 {sum(o['score'] > o['score_vs_2019'] for o in d)}/{len(d)}")
    (ROOT / "data" / "feud_validation2.json").write_text(json.dumps(out, ensure_ascii=False, indent=1))
    print(f"비용 ${router.total_cost:.3f}")


